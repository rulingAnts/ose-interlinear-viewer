#!/usr/bin/env node
// ============================================================
// check-versions.mjs — the five version sites must agree.
// ============================================================
//
// WHY THIS EXISTS
//
// The app's version is written down in five places, and nothing keeps
// them in step:
//
//   1. package.json                  "version"
//   2. package-lock.json             "version" (twice: root and packages[""])
//   3. src-tauri/tauri.conf.json     "version"        ← what the installer names itself
//   4. src-tauri/Cargo.toml          [package] version
//   5. src-tauri/Cargo.lock          the ose-interlinear-viewer [[package]] block
//
// The two LOCKFILES are the ones that rot, because they are not edited
// by hand — they are regenerated by `npm install` and `cargo build`, and
// a version bump that touches only the three hand-edited files leaves
// them behind silently. That is exactly the state this checker was
// written against: package.json, tauri.conf.json and Cargo.toml said
// 2.0.1 while both lockfiles still said 1.3.0.
//
// It matters because tauri.conf.json names the built installer and
// Cargo.lock is what actually gets compiled — a mismatch means the
// artifact you ship is not the version you think you shipped.
//
// Plain ESM, no dependencies, no framework. Run it directly:
//   node tools/check-versions.mjs
//
// Called from .githooks/pre-commit. Exits 1 when the sites disagree.
//
// TO FIX a disagreement: set the three hand-edited files to the target
// version, then regenerate the lockfiles rather than editing them:
//   npm install --package-lock-only
//   cargo update -p ose-interlinear-viewer --manifest-path src-tauri/Cargo.toml

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const read = (rel) => readFileSync(join(repoRoot, rel), 'utf8');
const has = (rel) => existsSync(join(repoRoot, rel));

// Each site reports { site, version } — or { site, error } if it could
// not be read at all. A site that cannot be parsed is a failure, not a
// silent skip: an unreadable site is indistinguishable from a wrong one.
const sites = [];
const add = (site, fn) => {
  try {
    const version = fn();
    if (!version) sites.push({ site, error: 'no version found' });
    else sites.push({ site, version });
  } catch (e) {
    sites.push({ site, error: e.message });
  }
};

// --- 1. package.json --------------------------------------------------
add('package.json', () => JSON.parse(read('package.json')).version);

// --- 2. package-lock.json --------------------------------------------
// Two places inside one file, and npm keeps them equal. Check both, and
// report them separately so a half-updated lockfile is visible.
add('package-lock.json (root)', () => JSON.parse(read('package-lock.json')).version);
add('package-lock.json (packages[""])', () => {
  const lock = JSON.parse(read('package-lock.json'));
  return lock.packages && lock.packages[''] && lock.packages[''].version;
});

// --- 3. src-tauri/tauri.conf.json ------------------------------------
add('src-tauri/tauri.conf.json', () => JSON.parse(read('src-tauri/tauri.conf.json')).version);

// --- 4. src-tauri/Cargo.toml -----------------------------------------
// Read the version from the [package] section only. A naive search for
// `version = ` would match the first dependency instead.
const crateName = (() => {
  const m = read('src-tauri/Cargo.toml').match(/^\s*\[package\]\s*$([\s\S]*?)(?=^\s*\[|\Z)/m);
  const nm = m && m[1].match(/^\s*name\s*=\s*"([^"]+)"/m);
  return nm ? nm[1] : null;
})();

add('src-tauri/Cargo.toml', () => {
  const section = read('src-tauri/Cargo.toml').match(/^\s*\[package\]\s*$([\s\S]*?)(?=^\s*\[|\Z)/m);
  if (!section) throw new Error('no [package] section');
  const m = section[1].match(/^\s*version\s*=\s*"([^"]+)"/m);
  return m ? m[1] : null;
});

// --- 5. src-tauri/Cargo.lock -----------------------------------------
// Find the [[package]] block whose name is this crate. Cargo.lock lists
// every dependency in the same shape, so the name match is required.
add('src-tauri/Cargo.lock', () => {
  if (!crateName) throw new Error('could not determine crate name from Cargo.toml');
  if (!has('src-tauri/Cargo.lock')) throw new Error('file not found');
  const blocks = read('src-tauri/Cargo.lock').split(/^\[\[package\]\]\s*$/m);
  for (const b of blocks) {
    const nm = b.match(/^\s*name\s*=\s*"([^"]+)"/m);
    if (nm && nm[1] === crateName) {
      const v = b.match(/^\s*version\s*=\s*"([^"]+)"/m);
      return v ? v[1] : null;
    }
  }
  throw new Error(`no [[package]] block named "${crateName}"`);
});

// --- Report -----------------------------------------------------------
const width = Math.max(...sites.map((s) => s.site.length));
console.log('check-versions: five version sites');
for (const s of sites) {
  console.log(`  ${s.site.padEnd(width)}  ${s.error ? `!! ${s.error}` : s.version}`);
}

const errored = sites.filter((s) => s.error);
const versions = [...new Set(sites.filter((s) => s.version).map((s) => s.version))];

if (errored.length === 0 && versions.length === 1) {
  console.log(`check-versions: OK — all ${sites.length} sites agree on ${versions[0]}.`);
  process.exit(0);
}

console.error('');
if (errored.length) {
  console.error(`check-versions: FAILED — ${errored.length} site(s) could not be read:`);
  for (const s of errored) console.error(`  ✗ ${s.site}: ${s.error}`);
}

if (versions.length > 1) {
  // Name the minority sites explicitly. "They disagree" is not actionable;
  // "these two are stale" is.
  const tally = new Map();
  for (const s of sites) if (s.version) tally.set(s.version, (tally.get(s.version) || 0) + 1);
  const majority = [...tally.entries()].sort((a, b) => b[1] - a[1])[0][0];
  const stale = sites.filter((s) => s.version && s.version !== majority);

  console.error(`check-versions: FAILED — sites disagree.`);
  console.error(`  ${tally.get(majority)} site(s) say ${majority}; these do not:`);
  for (const s of stale) console.error(`  ✗ ${s.site} is at ${s.version}, expected ${majority}`);
  console.error('');
  console.error('  Lockfiles are generated, not hand-edited. Regenerate them:');
  console.error('    npm install --package-lock-only');
  console.error('    cargo update -p ose-interlinear-viewer --manifest-path src-tauri/Cargo.toml');
}

process.exit(1);
